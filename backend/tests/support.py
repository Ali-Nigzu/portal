"""Disposable localhost PostgreSQL only; never connects through production ADC."""

import os
from contextlib import contextmanager
from datetime import datetime, timezone

import pg8000.dbapi
from fastapi import FastAPI
from fastapi.testclient import TestClient

from backend.app.api import auth, provider_auth
from backend.app.services.canonical_auth import CanonicalAuthRepository
from backend.app.services.provider_auth import ProviderAuth
from backend.app.services.provider_auth_repository import ProviderAuthRepository
from backend.app.services.provider_oidc import ProviderOIDC
from backend.app.services.user_lifecycle import UserLifecycle
from backend.app.services.user_lifecycle_repository import UserLifecycleRepository


class TestDatabase:
    def __init__(self):
        port = os.environ.get('CAMOS_TEST_POSTGRES_PORT')
        if not port:
            raise RuntimeError('Set CAMOS_TEST_POSTGRES_PORT for disposable localhost camos_auth_test only')
        self.port = int(port)

    def connect(self):
        return pg8000.dbapi.connect(host='127.0.0.1', port=self.port, user='camos_test',
                                   password='camos_test', database='camos_auth_test', timeout=5)

    @contextmanager
    def connection(self):
        connection = self.connect()
        connection.autocommit = True
        try:
            yield connection
        finally:
            connection.close()

    @contextmanager
    def transaction(self):
        connection = self.connect()
        try:
            yield connection
            connection.commit()
        except BaseException:
            connection.rollback()
            raise
        finally:
            connection.close()

    def execute(self, sql, params=()):
        with self.connection() as connection:
            cursor = connection.cursor()
            try:
                cursor.execute(sql, params)
                return cursor.fetchall() if cursor.description else None
            finally:
                cursor.close()

    def setup(self):
        # Test-only schema, matching the supplied live contract. This helper has
        # no configurable production host, database, principal or connector.
        self.execute('''CREATE TABLE IF NOT EXISTS users (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            email text NOT NULL, username text NOT NULL, phone_number text,
            password_hash text, status smallint NOT NULL, created_at timestamptz NOT NULL,
            session_version bigint NOT NULL DEFAULT 0)''')
        self.execute('CREATE UNIQUE INDEX IF NOT EXISTS uq_users_email_ci ON users(lower(email))')
        self.execute('''CREATE TABLE IF NOT EXISTS user_auth_identities (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            provider smallint NOT NULL CHECK(provider IN (0,1)), issuer text NOT NULL,
            subject text NOT NULL, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
            UNIQUE(provider,issuer,subject), UNIQUE(user_id,provider))''')
        self.execute('''CREATE TABLE IF NOT EXISTS user_lifecycle_challenges (
            id text PRIMARY KEY, purpose smallint NOT NULL, user_id bigint REFERENCES users(id),
            payload jsonb NOT NULL, code_hash text NOT NULL, code_expires_at timestamptz NOT NULL,
            attempts smallint NOT NULL DEFAULT 0, resends smallint NOT NULL DEFAULT 0,
            last_sent_at timestamptz NOT NULL, verified_at timestamptz, consumed_at timestamptz,
            created_at timestamptz NOT NULL)''')

    def reset(self):
        self.execute('TRUNCATE user_lifecycle_challenges,user_auth_identities,users RESTART IDENTITY CASCADE')

    def add_user(self, email='person@example.com', name='John Smith', password_hash=None, status=1, user_id=None):
        columns = 'email,username,password_hash,status,created_at'
        values = [email,name,password_hash,status,datetime.now(timezone.utc)]
        if user_id is not None:
            columns += ',id'; values.append(user_id)
        row = self.execute('INSERT INTO users(' + columns + ') VALUES(' + ','.join(['%s']*len(values))
                           + ') RETURNING id', tuple(values))[0]
        return CanonicalAuthRepository(self).get_enabled_user(int(row[0]))


def application(database):
    app = FastAPI()
    app.add_middleware(provider_auth.CallbackPrivacyMiddleware)
    app.include_router(auth.router)
    app.include_router(provider_auth.router)
    app.state.auth_repository = CanonicalAuthRepository(database)
    app.state.provider_auth = ProviderAuth(ProviderAuthRepository(database), ProviderOIDC())
    app.state.user_lifecycle = UserLifecycle(UserLifecycleRepository(database))
    return app


def client(app):
    value = TestClient(app, base_url='https://camos.app')
    value.headers.update({'Origin':'https://camos.app', 'X-Requested-With':'camOS'})
    return value
