 assert.equal(requests.filter(p=>p.includes('/dashboard/')&&p.endsWith('/snapshot')).length,1);
 await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
 console.log('Links',await page.locator('a').evaluateAll(nodes=>nodes.map(n=>({text:n.textContent,href:n.getAttribute('href')})).filter(n=>n.href?.includes('/demo/'))));
