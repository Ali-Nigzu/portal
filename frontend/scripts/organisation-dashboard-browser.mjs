 assert.equal(requests.filter(p=>p==='/api/demo/dashboard/sites/17/snapshot').length,1);
 await expect(page.getByRole('link',{name:'Event Logs',exact:true})).toHaveAttribute('href',/\/demo\/site-b\/event-logs/);
